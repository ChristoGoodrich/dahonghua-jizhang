#!/usr/bin/env node
// Regenerates flutter_app/integration_test/all_test.dart.
//
// Run after adding or removing an integration test file. With `--check` it
// exits non-zero when the file is stale instead of writing, which is what CI
// should call — a suite that silently stopped running one of its files is
// worse than one that fails.

const fs = require('node:fs');
const path = require('node:path');

const DIR = path.join(__dirname, '..', 'flutter_app', 'integration_test');
const OUT = path.join(DIR, 'all_test.dart');

const files = fs
  .readdirSync(DIR)
  .filter((f) => f.endsWith('_test.dart') && f !== 'all_test.dart')
  .sort();

const alias = (f) => f.slice(0, -'.dart'.length);

// Assembled by concatenation rather than as one template literal: the header
// talks about Dart code and wants backticks, which would end the literal.
const header = [
  '// Every integration test, under one entrypoint.',
  '//',
  '// Running them a file at a time builds and installs a whole APK per file.',
  `// At ${files.length} files that was ${files.length} builds for a suite whose execution takes`,
  '// seconds — about twenty minutes, nearly all of it Gradle. Worse than slow:',
  '// twenty minutes is twenty minutes in which the emulator can die, and twice',
  '// it did, costing the whole run rather than part of it. One entrypoint,',
  '// one build, about five minutes.',
  '//',
  '// Each file still stands alone and can still be run by itself. That is the',
  '// right thing to run while working on one screen; this is the right thing',
  '// to run before committing.',
  '//',
  '// Each file goes inside its OWN group, which is not cosmetic. A top-level',
  '// setUp in a file\'s main() is scoped to the whole SUITE, not to that file,',
  '// so calling the mains directly made every file\'s setUp run before every',
  '// other file\'s tests: account_detail_test creates two accounts in its',
  '// setUp, and that quietly broke four accounts_test cases that count how',
  '// many accounts exist. A group scopes setUp to itself — the isolation a',
  '// separate process used to provide for free.',
  '//',
  '// GENERATED by scripts/gen-all-tests.js — do not edit. Adding a test file',
  '// means re-running it; --check fails when this file is stale.',
  '',
  "import 'package:flutter_test/flutter_test.dart';",
  "import 'package:integration_test/integration_test.dart';",
  '',
];

const body = header
  .concat(files.map((f) => `import '${f}' as ${alias(f)};`))
  .concat([
    '',
    'void main() {',
    '  IntegrationTestWidgetsFlutterBinding.ensureInitialized();',
    '',
  ])
  .concat(files.map((f) => `  group('${alias(f)}', ${alias(f)}.main);`))
  .concat(['}', ''])
  .join('\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current.replace(/\r\n/g, '\n') !== body) {
    console.error(
      'all_test.dart is stale — run `node scripts/gen-all-tests.js`.\n' +
        'A test file that is not imported there is a test file that stopped running.'
    );
    process.exit(1);
  }
  console.log(`all_test.dart is current (${files.length} files)`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`${files.length} files -> ${path.relative(process.cwd(), OUT)}`);
}
