// Generates src/domain/gbkTable.ts — the GBK two-byte decode index used by the
// pure-JS fallback in src/domain/encoding.ts (Hermes has no TextDecoder('gbk')).
//
// Layout: 126 lead bytes (0x81-0xFE) × 190 trail bytes (0x40-0xFE minus 0x7F);
// cell index = (lead - 0x81) * 190 + (trail < 0x7F ? trail - 0x40 : trail - 0x41).
// Invalid pairs store U+FFFD; the decoder implements the WHATWG error rule
// (an ASCII trail byte is re-decoded as itself after the error).
//
// Run with any Node built with full ICU (default on official builds):
//   node scripts/gen-gbk-table.js
//
// The cells ICU has no Unicode assignment for land in the private use area,
// and a few graduate out of it between ICU versions (0xa2e3 → U+E76C on older
// builds, € on newer ones), so the table's PUA cells depend on the Node that
// generated it. encoding.test.ts excludes that area from its ICU comparison
// for exactly this reason.
const fs = require('fs');
const path = require('path');

const dec = new TextDecoder('gbk');
let table = '';
for (let lead = 0x81; lead <= 0xfe; lead++) {
  for (let trail = 0x40; trail <= 0xfe; trail++) {
    if (trail === 0x7f) continue;
    const s = dec.decode(new Uint8Array([lead, trail]));
    table += s.length === 1 ? s : '�';
  }
}

const out = `// AUTO-GENERATED by scripts/gen-gbk-table.js — do not edit by hand.
// GBK two-byte decode index (126 leads × 190 trails = ${table.length} cells),
// generated from the WHATWG/ICU 'gbk' TextDecoder so the pure-JS fallback in
// encoding.ts matches platform decoders exactly. U+FFFD marks invalid pairs.
export const GBK_INDEX =
  ${JSON.stringify(table)};
`;
fs.writeFileSync(path.resolve('src', 'domain', 'gbkTable.ts'), out, 'utf8');
console.log(`gbkTable.ts written: ${table.length} cells`);
